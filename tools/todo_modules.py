#!/usr/bin/env python3
"""Write docs/TODO-MODULES.md: every code-module function still in assembly, grouped by shape.

Run from the repository root with the toolchain loaded (decomp-kit's `dk` on PATH), after `make split-modules`:

    python3 tools/todo_modules.py

A shape is one function as it appears in every module that carries a copy: the same instruction words once calls and
addresses into the module itself are masked (modules load at 0x1E00000; their own addresses differ, the code does
not). One C file matches every copy. Rows are ordered smallest first, then most copies.

Kinds:
  work    needs C
  spread  a copy of this shape is already C in another module: copy that C over (rename the module labels)
  switch  uses a jump table
  piece   no C compiles to it alone (an epilogue with no prologue and the like; the kit's piece test)
Notes come from config/module_notes.tsv (earlier tries, why a hard one is hard); real names from
config/module_names.tsv (the Japanese release's symbol table)."""
import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path

import rabbitizer

ROOT = Path(__file__).resolve().parent.parent
WORD = re.compile(r"/\* [0-9A-F]+ ([0-9A-F]{8}) ([0-9A-F]{8}) \*/")
NAME = re.compile(r"func_([0-9A-F]{8})_([bcm]\d{3})$")
MOD_LO, MOD_HI = 0x1E00000, 0x2000000

dk = shutil.which("dk")
if not dk:
    sys.exit("dk not found: load the toolchain first (. ~/decomp/toolchain/env.sh)")
sys.path.insert(0, str(Path(dk).resolve().parent))
sys.argv = [sys.argv[0]]
import dk as dkmod  # noqa: E402


def words_of(path):
    text = path.read_text().split("endlabel")[0]
    return [(int(v, 16), int.from_bytes(bytes.fromhex(w), "little")) for v, w in WORD.findall(text)], "jtbl_" in text


def masked(words):
    out = []
    for vram, w in words:
        op = w >> 26
        if op == 3 and MOD_LO <= (((vram + 4) & 0xF0000000) | ((w & 0x03FFFFFF) << 2)) < MOD_HI:
            w &= 0xFC000000
        elif op == 0x0F and (w & 0xFFFF) in (0x1E0, 0x1E1):
            w &= 0xFFFF0000
        out.append(w)
    return tuple(out)


def tag(fn):
    m = NAME.match(fn)
    return f"{m.group(2)}:{m.group(1)}"


def tsv(name):
    path = ROOT / "config" / name
    return [ln.split("\t") for ln in path.read_text().splitlines()[1:]] if path.exists() else []


p = dkmod.Project.find()
rem = {f for f, c in p.remaining().items() if dkmod.is_module_file(p, c)}
cat = rabbitizer.InstrCategory.R5900
todo = {f: words_of(p.func_asm(f)) for f in rem}
done = {}
for path in ROOT.glob("asm/matchings/mod/*/*.s"):
    if path.stem not in rem:
        w, _ = words_of(path)
        if w:
            done[masked(w)] = path.stem
names = {f"{c[0]}:{c[1]}": c[2] for c in tsv("module_names.tsv") if len(c) > 2}
notes = {c[0]: (c[1], c[2]) for c in tsv("module_notes.tsv") if len(c) > 2}

groups = defaultdict(list)
for f, (w, _) in todo.items():
    groups[masked(w)].append(f)
rows = []
for key, members in groups.items():
    members.sort(key=lambda n: (NAME.match(n).group(2), n))
    w, sw = todo[members[0]]
    tags = [tag(m) for m in members]
    piece = dkmod.piece_reason(w, cat)
    twin = done.get(key)
    kind = "piece" if piece else "spread" if twin else "switch" if sw else "work"
    best, note = next((notes[t] for t in tags if t in notes), ("", ""))
    if twin:
        note = f"copy of {twin}" + (f"; {note}" if note else "")
    elif piece:
        note = piece + (f"; {note}" if note else "")
    rows.append((len(w), -len(members), tags[0], members[0], kind, next((names[t] for t in tags if t in names), ""),
                 best, note, tags[1:]))
rows.sort()

total = sum(-r[1] for r in rows)
by = defaultdict(lambda: [0, 0, 0])
for r in rows:
    by[r[4]][0] += 1
    by[r[4]][1] += -r[1]
    by[r[4]][2] += -r[1] * r[0]
hard = sum(1 for r in rows if r[7].startswith("hard:"))
out = ["# Code-module functions still in assembly", "",
       "Generated by `python3 tools/todo_modules.py` (run it from the repository root with the toolchain loaded, after "
       "`make split-modules`); do not edit by hand. Re-run it after you match something.", "",
       f"**{total} functions in {len(rows)} shapes.** A shape is one function as it appears in every module that "
       "carries a copy: one C file matches all of them (see AGENTS.md, \"Copies\"). Order: smallest first, then most "
       f"copies. {hard} shapes are marked **hard**: an earlier serious try missed, and the note says why; the best "
       "draft, where there is one, is in `drafts/mod/`.", "",
       "| kind | shapes | functions | instructions |", "|---|---|---|---|"]
for k in ("work", "spread", "switch", "piece"):
    if k in by:
        a, b, c = by[k]
        out.append(f"| {k} | {a} | {b} | {c} |")
out += ["", "Kinds: **work** needs C; **spread** = a copy is already C in another module (copy it over); **switch** = "
        "uses a jump table; **piece** = no C compiles to it alone (leave it for last).", "",
        "| # | shape | function | insns | copies | kind | real name | best so far | note |",
        "|---|---|---|---|---|---|---|---|---|"]
for i, r in enumerate(rows, 1):
    note = r[7].replace("|", "/")
    if r[8]:
        more = ", ".join(r[8][:6]) + (f", +{len(r[8]) - 6}" if len(r[8]) > 6 else "")
        note = (note + "; " if note else "") + "also in " + more
    out.append(f"| {i} | {r[2]} | `{r[3]}` | {r[0]} | {-r[1]} | {r[4]} | {r[5]} | {r[6]} | {note} |")
(ROOT / "docs/TODO-MODULES.md").write_text("\n".join(out) + "\n")
print(f"docs/TODO-MODULES.md: {total} functions, {len(rows)} shapes, {hard} hard")
